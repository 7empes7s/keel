/** Reads the recovered tables straight out of a database handle, for comparison. */
async function readHistory(connect, tenantRef) {
  const client = await connect();
  try {
    const out = {};
    for (const [table, columns] of DUMP_TABLES) {
      const { rows } = await client.query(`SELECT ${columns.join(', ')} FROM ${table} ORDER BY 1`);
      out[table] = rows;
    }
    out.chain = await verifyChain(client, { tenantRef });
    return out;
  } finally {
    await client.end();
  }
}

test('empty disposable instance recovers fixture history with writers disabled', async () => {
  const result = await reconstructRecovery(baseOptions());
  assert.equal(result.ok, true, JSON.stringify(result.failures));
  assert.equal(result.stage, 'recovered');
  assert.equal(result.readOnly, true);
  assert.equal(result.writersDisabled, true);
  assert.equal(result.identity.principalId, 'recovery-officer@example.test');
  assert.equal(result.identity.independent, true);
  assert.equal(result.recoveryComplete, true);
  assert.deepEqual(result.incomplete, []);

  // The named fixture history landed in the empty disposable instance.
  assert.equal(result.recovered.schedules.length, 6);
  assert.deepEqual(
    result.recovered.schedules.map((row) => `${row.job_kind}:${row.tier ?? ''}`).sort(),
    ['api-drift:', 'collect:tier1', 'collect:tier2', 'collect:tier3', 'offsite:', 'prune:'],
  );
  assert.equal(result.recovered.approvals.length, 2);
  assert.deepEqual(
    result.recovered.approvals.map((row) => row.status).sort(),
    ['approved', 'rejected'],
  );
  assert.equal(result.recovered.jobCount, 1, 'the approved request minted exactly one job');
  assert.equal(result.recovered.principals.length, 2);
  assert.equal(result.recovered.grants.length, 2);
  assert.deepEqual(
    result.recovered.grants.map((row) => row.role).sort(),
    ['approver', 'operator'],
  );
  assert.deepEqual(result.recovered.evidence, {
    chainOk: true,
    headSeq: fixture.checkpoint.headSeq,
    headHash: fixture.checkpoint.headHash,
    recordCount: fixture.checkpoint.recordCount,
  });

  // Row-for-row, the disposable instance reproduces the source history.
  const expected = await readHistory(() => source.connect(), TENANT);
  const actual = await readHistory(() => result.target.connect(), TENANT);
  assert.deepEqual(
    JSON.parse(JSON.stringify(actual)),
    JSON.parse(JSON.stringify(expected)),
    'schedules, approvals, grants, evidence and the chain head round-trip byte-equal',
  );
  assert.deepEqual(actual.chain, { ok: true });

  // Mutation pin: enable writes during reconstruction. The access session is
  // read-only at the database level — a write on the RAW connection fails
  // with SQLSTATE 25006 even if the statement guard were bypassed.
  await assert.rejects(
    result.access.client.query(`INSERT INTO evidence (tenant_ref, kind, subject, actor, record_hash)
      VALUES ('${TENANT}', 'tamper', '{}'::jsonb, 'tamper', 'x')`),
    (error) => error.code === '25006',
  );
  // The statement guard refuses writes before they reach the database —
  // including a writable CTE smuggled behind a leading WITH.
  await assert.rejects(result.access.query('DELETE FROM evidence'), RecoveryReadOnlyError);
  await assert.rejects(result.access.query('  update schedule set enabled = false'), RecoveryReadOnlyError);
  await assert.rejects(
    result.access.query('WITH d AS (DELETE FROM evidence RETURNING *) SELECT * FROM d'),
    RecoveryReadOnlyError,
  );
  // Reads still work through the guard.
  const { rows } = await result.access.query('SELECT count(*)::int AS n FROM schedule WHERE tenant_ref = $1', [TENANT]);
  assert.equal(rows[0].n, 6);

  await result.access.client.end();
});

/** COPY text-format encoding of one value, as pg_dump writes it. */
function copyField(value) {
  if (value === null) return '\\N';
  return value.replaceAll('\\', '\\\\').replaceAll('\t', '\\t').replaceAll('\n', '\\n').replaceAll('\r', '\\r');
}

/**
 * Renders the source tables the way plain pg_dump 16.10+ does: \restrict,
 * session SETs, DDL that collides with the pinned schema, a function body
 * holding ';' and a line starting with COPY, COPY blocks (here children
 * before parents) and a public.-qualified setval.
 */
async function renderPgDumpSql(client) {
  const out = [
    '--',
    '-- PostgreSQL database dump',
    '--',
    '',
    '\\restrict fixtureRestrictKey0123456789',
    '',
    "SET statement_timeout = 0;",
    "SET client_encoding = 'UTF8';",
    "SET standard_conforming_strings = on;",
    "SELECT pg_catalog.set_config('search_path', '', false);",
    '',
    'CREATE TABLE public.principal (',
    '    id uuid NOT NULL',
    ');',
    '',
    'CREATE FUNCTION public.fixture_fn() RETURNS void',
    '    LANGUAGE plpgsql',
    '    AS $_$',
    'BEGIN',
    "COPY principal TO stdout; RAISE NOTICE 'not; a statement';",
    'END',
    '$_$;',
    '',
  ];
  for (const [table, columns] of [...DUMP_TABLES].reverse()) {
    const { rows } = await client.query(
      `SELECT ${columns.map((column) => `${column}::text AS ${column}`).join(', ')} FROM ${table} ORDER BY 1`,
    );
    out.push(`COPY public.${table} (${columns.join(', ')}) FROM stdin;`);
    for (const row of rows) out.push(columns.map((column) => copyField(row[column])).join('\t'));
    out.push('\\.', '');
  }
  const { rows: [{ max }] } = await client.query('SELECT max(seq)::text AS max FROM evidence');
  out.push(`SELECT pg_catalog.setval('public.evidence_seq_seq', ${max}, true);`, '');
  out.push('ALTER TABLE ONLY public.principal', '    ADD CONSTRAINT principal_pkey PRIMARY KEY (id);', '');
  out.push('\\unrestrict fixtureRestrictKey0123456789', '');
  return out.join('\n');
}

/** Writes a dump and returns reconstruction options whose manifest pins it. */
async function optionsForDump(name, sql) {
  const bytes = gzipSync(sql);
  const path = join(tmp, name);
  await writeFile(path, bytes);
  const manifest = structuredClone(fixture.manifest);
  manifest.dump = { ...fixture.manifest.dump, path, sha256: sha256Hex(bytes), bytes: bytes.length };
  return baseOptions({ manifest, dumpPath: path });
}

async function assertRoundTrip(result) {
  assert.equal(result.ok, true, JSON.stringify(result.failures));
  assert.equal(result.stage, 'recovered');
  const expected = await readHistory(() => source.connect(), TENANT);
  const actual = await readHistory(() => result.target.connect(), TENANT);
  assert.deepEqual(JSON.parse(JSON.stringify(actual)), JSON.parse(JSON.stringify(expected)));
  await result.access.client.end();
}

test('a pg_dump-format dump (\\restrict, COPY blocks out of foreign-key order, colliding DDL) reconstructs the same history', async () => {
  const result = await reconstructRecovery(await optionsForDump('dump-pgdump.sql.gz', await renderPgDumpSql(sourceClient)));
  await assertRoundTrip(result);
});

test('a real pg_dump of the source reconstructs the same history', async (t) => {
  const url = process.env.KEEL_DB_TEST_URL;
  const dump = spawnSync('pg_dump', ['--schema', source.schema, url], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (dump.error || dump.status !== 0) {
    t.skip(`pg_dump unavailable for this server: ${dump.error?.message ?? dump.stderr.trim()}`);
    return;
  }
  // The source lives in an isolated test schema; production dumps name public.
  const sql = dump.stdout.replaceAll(`"${source.schema}"`, 'public').replaceAll(source.schema, 'public');
  assert.match(sql, /^COPY public\.evidence /m, 'the real dump carries COPY blocks');
  const result = await reconstructRecovery(await optionsForDump('dump-real.sql.gz', sql));
  await assertRoundTrip(result);
});

