test('read-only session guard: unit pins', async () => {
  const client = await source.connect();
  try {
    const access = await openRecoveryReadOnlySession(client);
    assert.equal(access.readOnly, true);
    // Reads pass.
    await access.query('SELECT 1');
    await access.query('WITH x AS (SELECT 1) SELECT * FROM x');
    await access.query("VALUES (1)");
    await access.query('TABLE evidence_head');
    await access.query('EXPLAIN SELECT 1');
    await access.query('SELECT updated_at, created_at FROM schedule');
    // Keywords the guard refuses are data inside string literals, dollar
    // quotes, quoted identifiers and comments — never false positives.
    await access.query("SELECT '-- DELETE FROM evidence; SET default_transaction_read_only = off' AS note");
    await access.query('SELECT $$update evidence set enabled = false$$ AS a, $tag$DELETE;$tag$ AS b');
    await access.query('SELECT 1 /* DELETE FROM evidence; SELECT 1 */');
    // Writes are refused by the guard and by the database.
    for (const sql of [
      // Direct writes.
      'INSERT INTO principal (email) VALUES (\'x\')',
      'UPDATE principal SET email = \'x\'',
      'DELETE FROM principal',
      'DROP TABLE principal',
      'TRUNCATE principal',
      // Writable CTEs and DML after a WITH clause — the leading WITH must
      // not smuggle them past the guard (KEEL-VERIFY: writable CTE).
      'WITH d AS (DELETE FROM evidence RETURNING *) SELECT * FROM d',
      'with u as (update schedule set enabled = false returning *) select * from u',
      'WITH i AS (INSERT INTO principal (email) VALUES (\'x\') RETURNING *) SELECT * FROM i',
      'WITH x AS (SELECT 1) DELETE FROM evidence',
      'WITH x AS (SELECT 1) UPDATE principal SET email = \'x\'',
      // Transaction-mode resets and multi-statement smuggling (KEEL-VERIFY:
      // resetting transaction mode).
      'SET default_transaction_read_only = off',
      'RESET ALL',
      'SELECT 1; SET default_transaction_read_only = off',
      'SELECT 1; DELETE FROM evidence',
      'SELECT 1;',
      "SELECT set_config('default_transaction_read_only', 'off', false)",
      // EXPLAIN ANALYZE executes the explained statement; SELECT INTO writes.
      'EXPLAIN ANALYZE DELETE FROM evidence',
      'EXPLAIN (ANALYZE) SELECT 1',
      'SELECT * INTO scratch FROM schedule',
      // Sequence state mutation.
      "SELECT nextval('evidence_seq_seq')",
      "SELECT setval('evidence_seq_seq', 1)",
    ]) {
      await assert.rejects(access.query(sql), RecoveryReadOnlyError, sql);
    }
    await assert.rejects(client.query("INSERT INTO principal (email) VALUES ('x')"), (e) => e.code === '25006');
    // The mode-reset attempts did not bend the session: it is still read-only.
    const { rows: [mode] } = await access.query('SHOW transaction_read_only');
    assert.equal(mode.transaction_read_only, 'on');
  } finally {
    await client.end();
  }
});

