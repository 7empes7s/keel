function sqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL';
  if (value instanceof Date) return `'${value.toISOString()}'::timestamptz`;
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (typeof value === 'number' || typeof value === 'bigint') return String(value);
  if (typeof value === 'object') return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

/** Renders the source tables as an executable INSERT dump. */
async function renderDumpSql(client, { corruptEvidenceHash = false, omitTables = [] } = {}) {
  const statements = ['-- keel fixture dump generated by engine/roadmap/keel-recovery.test.mjs'];
  for (const [table, columns] of DUMP_TABLES) {
    if (omitTables.includes(table)) continue;
    const { rows } = await client.query(`SELECT ${columns.join(', ')} FROM ${table} ORDER BY 1`);
    if (rows.length === 0) continue;
    const values = rows.map((row) => `(${columns.map((column) => {
      let value = row[column];
      if (corruptEvidenceHash && table === 'evidence' && column === 'record_hash' && row.seq === rows[0].seq) {
        value = '0'.repeat(64);
      }
      return sqlLiteral(value);
    }).join(', ')})`);
    statements.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values.join(',\n')};`);
  }
  statements.push(`SELECT setval('evidence_seq_seq', (SELECT max(seq) FROM evidence));`);
  return statements.join('\n');
}

/** Populates the source tenant history: schedules, approvals, grants, evidence. */
async function buildSourceFixture() {
  sourceClient = await source.connect();
  await sourceClient.query(readFileSync(new URL('../store/schema.sql', import.meta.url), 'utf8'));

  // Grants: an operator (requester) and an approver.
  const { rows: [requester] } = await sourceClient.query(
    `INSERT INTO principal (email, display_name) VALUES ($1, $2) RETURNING *`,
    ['requester@example.test', 'Fixture Requester'],
  );
  const { rows: [approver] } = await sourceClient.query(
    `INSERT INTO principal (email, display_name) VALUES ($1, $2) RETURNING *`,
    ['approver@example.test', 'Fixture Approver'],
  );
  for (const [principal, role] of [[requester, 'operator'], [approver, 'approver']]) {
    await sourceClient.query(
      `INSERT INTO role_grant (principal_id, role, granted_by, reason) VALUES ($1, $2, $3, $4)`,
      [principal.id, role, 'fixture-admin', 'fixture grant'],
    );
  }

  // Schedules: the standard six for this tenant, plus another tenant's six
  // in the same table/dump — the reconstructed read must return only the
  // requested tenant's rows even though both are physically present.
  await seedSchedules(sourceClient, { tenantRef: TENANT });
  await seedSchedules(sourceClient, { tenantRef: OTHER_TENANT });

  // Approvals: one approved (mints a job), one rejected — both on evidence.
  const approved = await requestApproval(sourceClient, {
    tenantRef: TENANT,
    action: 'collect',
    params: { tier: 'tier1' },
    requestedBy: requester.id,
    justification: 'fixture approval to approve',
  });
  await approveRequest(sourceClient, { tenantRef: TENANT, id: approved.id, decidedBy: approver.id });
  const rejected = await requestApproval(sourceClient, {
    tenantRef: TENANT,
    action: 'collect',
    params: { tier: 'tier3' },
    requestedBy: requester.id,
    justification: 'fixture approval to reject',
  });
  await rejectRequest(sourceClient, {
    tenantRef: TENANT, id: rejected.id, decidedBy: approver.id, reason: 'fixture rejection',
  });
  await appendEvidence(sourceClient, {
    tenantRef: TENANT,
    kind: 'backup-complete',
    subject: { dump: 'fixture' },
    actor: 'fixture-operator',
    eventSink: QUIET_SINK,
  });

  // A completed snapshot + configuration export for the manifest link.
  const snapshotId = await createSnapshot(sourceClient, { tenantRef: TENANT });
  await insertResourceVersion(sourceClient, {
    snapshotId,
    resource: {
      naturalKey: 'user:ana@example.test',
      resourceType: 'user',
      payload: { id: 'u1', userPrincipalName: 'ana@example.test', displayName: 'Fixture User' },
      payloadHash: 'fixture-hash',
      criticality: 'tier1',
      blastRadius: 'access-affecting',
      fidelity: 'read-only',
      provenance: { adapter: 'fixture', collectedAt: '2026-09-22T00:00:00.000Z', fidelity: 'read-only' },
    },
  });
  await completeSnapshot(sourceClient, {
    id: snapshotId,
    status: 'complete',
    coverageDigest: { ...fullSuccessfulCoverageDigest(), user: { outcome: 'complete', itemCount: 1 } },
  });
  const { exportDir } = await exportSnapshot(sourceClient, {
    tenantRef: TENANT, snapshotId, exportRoot: join(tmp, 'export'),
  });
  const exportManifestBytes = await readFile(join(exportDir, 'manifest.json'));
  const exportManifest = JSON.parse(exportManifestBytes.toString('utf8'));

  // The dump artifact over the populated history.
  const dumpBytes = gzipSync(await renderDumpSql(sourceClient));
  const dumpPath = join(tmp, 'dump.sql.gz');
  await writeFile(dumpPath, dumpBytes);

  const { rows: [head] } = await sourceClient.query(
    'SELECT head_seq, head_hash, record_count FROM evidence_head WHERE tenant_ref = $1',
    [TENANT],
  );
  const checkpoint = {
    headSeq: Number(head.head_seq),
    headHash: head.head_hash,
    recordCount: Number(head.record_count),
  };

  const manifest = buildRecoveryManifest({
    tenantRef: TENANT,
    build: { revision: BUILD_REVISION, schemaPin },
    dump: { path: dumpPath, sha256: sha256Hex(dumpBytes), bytes: dumpBytes.length },
    observationIds: Object.keys(exportManifest.types).map((type) => `${snapshotId}:${type}`),
    configExport: {
      manifestPath: join(exportDir, 'manifest.json'),
      manifestSha256: sha256Hex(exportManifestBytes),
    },
    evidenceCheckpoint: checkpoint,
    residency: { provider: 'local-disk', region: 'on-prem datacenter A' },
    keyRecovery: {
      heldBy: 'security officer',
      location: 'offline safe, sealed envelope #7',
      instructions: 'Retrieve envelope #7 from the offline safe; the passphrase is held separately.',
    },
  });
  const manifestPath = join(tmp, 'recovery.json');
  await writeFile(manifestPath, `${JSON.stringify(manifest)}\n`);

  return {
    snapshotId, exportDir, dumpBytes, dumpPath, checkpoint, manifest, manifestPath,
    build: { revision: BUILD_REVISION, schemaPin },
    principals: { requester, approver },
  };
}

