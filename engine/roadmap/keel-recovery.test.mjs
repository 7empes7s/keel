test('COPY text fields decode NULL, escapes, octal and hex bytes', () => {
  assert.equal(decodeCopyField('\\N'), null);
  assert.equal(decodeCopyField('plain'), 'plain');
  assert.equal(decodeCopyField('a\\tb\\nc\\\\d\\re'), 'a\tb\nc\\d\re');
  assert.equal(decodeCopyField('\\303\\251t\\xc3\\xa9'), 'été');
  assert.equal(decodeCopyField('\\\\x0a'), '\\x0a', 'a bytea literal survives');
  const items = parseDump("\\restrict k\nCOPY public.t (a, b) FROM stdin;\n1\t\\N\n\\.\nSELECT 'x;y';\n\\unrestrict k\n");
  assert.deepEqual(items.map((item) => item.kind), ['meta', 'copy', 'sql', 'meta']);
  assert.deepEqual(items[1].rows, ['1\t\\N']);
  assert.equal(items[2].text, "SELECT 'x;y'");
});

