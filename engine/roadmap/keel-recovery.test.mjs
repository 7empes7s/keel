test('anonymous or unauthenticated recovery identity is refused (mutation pin)', async () => {
  let created = 0;
  const spyTarget = async () => { created += 1; return newTarget(); };
  let authenticatorCalls = 0;
  const countingAuthenticator = async () => { authenticatorCalls += 1; return true; };

  // Anonymous emergency identity: refused before the authenticator is even
  // consulted. A mutator deleting the anonymous branch fails this test.
  let result = await reconstructRecovery(baseOptions({
    identity: { anonymous: true, principalId: 'emergency', credentialRef: 'break-glass' },
    authenticator: countingAuthenticator,
    createTargetDatabase: spyTarget,
  }));
  assert.equal(result.ok, false);
  assert.equal(result.stage, 'identity');
  assert.ok(result.failures.some((f) => f.includes('anonymous recovery identity is refused')));
  assert.equal(authenticatorCalls, 0);
  assert.equal(created, 0);

  // Missing principal id is equally anonymous.
  result = await reconstructRecovery(baseOptions({
    identity: { credentialRef: 'break-glass' },
    authenticator: countingAuthenticator,
    createTargetDatabase: spyTarget,
  }));
  assert.equal(result.ok, false);
  assert.equal(result.stage, 'identity');
  assert.equal(authenticatorCalls, 0);

  // No independent authenticator configured: this process cannot authenticate
  // anyone by itself.
  result = await reconstructRecovery(baseOptions({ authenticator: undefined, createTargetDatabase: spyTarget }));
  assert.equal(result.ok, false);
  assert.equal(result.stage, 'identity');
  assert.ok(result.failures.some((f) => f.includes('independent authenticator')));

  // The independent channel refuses.
  result = await reconstructRecovery(baseOptions({ authenticator: async () => false, createTargetDatabase: spyTarget }));
  assert.equal(result.ok, false);
  assert.equal(result.stage, 'identity');
  assert.ok(result.failures.some((f) => f.includes('refused recovery identity')));

  // A truthy-but-not-`true` decision (an object, a non-empty string, a
  // non-zero number) must be refused just like `false`. A mutator loosening
  // `decision !== true` to `!decision` would accept these and fails here.
  for (const nonTrueDecision of [{ ok: false }, 'false', 1, [], 'true']) {
    result = await reconstructRecovery(baseOptions({
      authenticator: async () => nonTrueDecision,
      createTargetDatabase: spyTarget,
    }));
    assert.equal(result.ok, false, `decision ${JSON.stringify(nonTrueDecision)} must be refused`);
    assert.equal(result.stage, 'identity');
    assert.ok(result.failures.some((f) => f.includes('refused recovery identity')));
  }

  // A credential reference that IS credential material is refused (GC#6).
  result = await reconstructRecovery(baseOptions({
    identity: { principalId: 'recovery-officer@example.test', credentialRef: 'password=hunter2' },
    authenticator: countingAuthenticator,
    createTargetDatabase: spyTarget,
  }));
  assert.equal(result.ok, false);
  assert.equal(result.stage, 'identity');
  assert.equal(created, 0, 'identity refusals never reach the database');

  // The authenticator receives exactly the claimed identity.
  let seen = null;
  result = await reconstructRecovery(baseOptions({
    authenticator: async (claimed) => { seen = claimed; return true; },
  }));
  assert.equal(result.ok, true, JSON.stringify(result.failures));
  assert.deepEqual(seen, {
    principalId: 'recovery-officer@example.test',
    credentialRef: 'break-glass token reference: safe #7, held by security officer',
  });
  await result.access.client.end();

  // Unit-level pins on the authz module itself.
  await assert.rejects(
    authenticateRecoveryIdentity({ identity: { anonymous: true }, authenticator: async () => true }),
    RecoveryIdentityError,
  );
  await assert.rejects(
    authenticateRecoveryIdentity({ identity: null, authenticator: async () => true }),
    RecoveryIdentityError,
  );
  await assert.rejects(
    authenticateRecoveryIdentity({ identity: { principalId: 'p', credentialRef: 'c' } }),
    /independent authenticator/,
  );
  for (const nonTrueDecision of [{ ok: false }, 'false', 1, [], 'true']) {
    await assert.rejects(
      authenticateRecoveryIdentity({
        identity: { principalId: 'p', credentialRef: 'c' },
        authenticator: async () => nonTrueDecision,
      }),
      RecoveryIdentityError,
      `decision ${JSON.stringify(nonTrueDecision)} must be refused`,
    );
  }
  const token = await authenticateRecoveryIdentity({
    identity: { principalId: 'p', credentialRef: 'c' },
    authenticator: async () => true,
    at: new Date('2026-09-22T00:00:00.000Z'),
  });
  assert.equal(token.independent, true);
  assert.equal(token.authenticatedAt, '2026-09-22T00:00:00.000Z');
  assert.ok(Object.isFrozen(token));
});

