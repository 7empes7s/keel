/** The plain words for one record field, or null when the label has no entry. */
export function fieldInfo(raw: string): FieldInfo | null {
  const exact = RECORD_GLOSSARY[raw];
  if (exact) return exact;
  // "Base label · item name": the base has the words, the item name stays.
  const split = raw.indexOf(" · ");
  if (split > 0) {
    const base = RECORD_GLOSSARY[raw.slice(0, split)];
    if (base) return { ...base, label: `${base.label} · ${raw.slice(split + 3)}` };
  }
  for (const { pattern, key, label } of PATTERNS) {
    const match = raw.match(pattern);
    const info = match ? RECORD_GLOSSARY[key] : undefined;
    if (match && info) return { ...info, label: label ? label(match) : info.label };
  }
  return null;
}
