// What every "Technical details" field means, in words a non-expert reads.
//
// Each field a page puts in a record (components/technical-details.tsx, RecordField)
// is looked up here by the label the page passes. The entry gives the plain label the
// panel shows, a one-line meaning, how to format the value, and whether the field is
// for support only (IDs, codes, commands, hashes), in which case it stays behind the
// panel's "Show support details" switch. Error fields show a short line and keep the
// full text behind a click.
//
// portal/test/record-glossary.test.ts reads every RecordField in the portal and fails
// when a label has no entry here, so a new field cannot ship without plain words.

import { fieldWords } from "@/lib/changes-view";
import type { DisplayEnumGroup } from "@/lib/presentation";

export type FieldFormat = "duration-ms" | "duration-s" | "count" | "bytes";

export type FieldInfo = {
  /** The plain label shown in the panel. */
  label: string;
  /** One line on what the value means. */
  meaning: string;
  /** IDs, codes, commands, hashes and versions: shown only with support details on. */
  support?: boolean;
  /** An error text: a short line, the full text only on click. */
  error?: boolean;
  format?: FieldFormat;
  /** Yes/No fields: which answer is good (green); the other is amber. */
  goodWhen?: boolean;
  /** Count fields where any number above 0 needs attention. */
  zeroIsGood?: boolean;
  /** Why the value can be missing and what to do about it. */
  missing?: string;
  /** Stored codes in this field read through this group of lib/presentation's DISPLAY_ENUMS. */
  enum?: DisplayEnumGroup;
};

type Extra = Omit<FieldInfo, "label" | "meaning">;

const fact = (label: string, meaning: string, extra: Extra = {}): FieldInfo => ({ label, meaning, ...extra });
const support = (label: string, meaning: string, extra: Extra = {}): FieldInfo => ({ label, meaning, support: true, ...extra });
const error = (label: string, meaning: string): FieldInfo => ({ label, meaning, error: true });
const ms = (label: string, meaning: string, missing?: string): FieldInfo => ({ label, meaning, format: "duration-ms", missing });
const count = (label: string, meaning: string, extra: Extra = {}): FieldInfo => ({ label, meaning, format: "count", ...extra });
const yesNo = (label: string, meaning: string, goodWhen?: boolean): FieldInfo => ({ label, meaning, goodWhen });

